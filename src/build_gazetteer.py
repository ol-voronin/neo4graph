"""National settlements gazetteer from the official KATOTTG codifier (Мінрозвитку / Мінрегіон), replacing the
Kharkiv-only local/gazetteer.json as the source of truth for "place name -> oblast".

  python src/build_gazetteer.py                 # download the newest codifier, write geo/gazetteer_ua.json
  python src/build_gazetteer.py --xlsx f.xlsx   # use a local copy (no network)
  python src/build_gazetteer.py --sql           # also regenerate db/migrations/016_rule_geo.sql from the JSON

Source: the codifier page lists every edition (kodifikator-DD-MM-YYYY.xlsx); the newest link on the page is taken,
data.gov.ua (2021 edition, no 2024 renames) is the fallback. Needs openpyxl for reading xlsx.

Output geo/gazetteer_ua.json (committed, compact):
  {"edition": url, "regions": [slug, ...],
   "places": {"<lowercase name>": "<region idx><category>[,<region idx><category>...]"}, ...}
  category: K city with special status, M city, X selyshche, C village, B city district (KATOTTG letters).
  A name shared by several oblasts keeps every (oblast, category) pair: the caller decides (see resolve()).

The SQL migration only uses cities (K, M) plus manual aliases and Russian stems from geo/gazetteer_extra.json:
villages are far too ambiguous for a regex (the same village name exists in up to 20 oblasts).
"""
import argparse
import json
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from oblasts import EXTRA_AREAS, OBLASTS, slug_for_codifier  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GEO = ROOT / "geo"
PAGE = "https://mindev.gov.ua/diialnist/rozvytok-mistsevoho-samovriaduvannia/kodyfikator-administratyvno-terytorialnykh-odynyts-ta-terytorii-terytorialnykh-hromad"
FALLBACK = "https://data.gov.ua/dataset/2f4beef4-6bba-43d3-9e9e-120c696f1123/resource/baa61b78-4e0d-499f-89d9-f2863abdb094/download/kodifikator.xlsx"
UA = {"User-Agent": "Mozilla/5.0 (research; rhetoric-strikes)"}
APOS = str.maketrans({"’": "'", "ʼ": "'", "`": "'", "‘": "'"})
REGIONS = sorted(OBLASTS) + sorted(EXTRA_AREAS.values())


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.translate(APOS).strip().lower())


def newest_url() -> str:
    try:
        page = urllib.request.urlopen(urllib.request.Request(PAGE, headers=UA), timeout=60).read().decode("utf-8", "replace")
        links = re.findall(r'href="([^"]+kodifikator[^"]*\.xlsx)"', page)
        if links:
            return links[0]  # the page lists editions newest first
    except Exception as e:  # noqa: BLE001
        print("codifier page unreachable:", e)
    return FALLBACK


def read_codifier(path: Path):
    """Yield (region_slug, category, name) for every object below level 1."""
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True)
    ws = wb.worksheets[0]
    l1_slug = {}
    for row in ws.iter_rows(values_only=True):
        if not row or not row[0] or not str(row[0]).startswith("UA") or len(row) < 7:
            continue
        l1, cat, name = str(row[0]), (row[5] or "").strip(), (row[6] or "").strip()
        if cat in ("O", "K") and not row[1]:
            l1_slug[l1] = slug_for_codifier(name)
            if cat == "K":
                yield l1_slug[l1], "K", name
            continue
        slug = l1_slug.get(l1)
        if slug and cat in ("M", "X", "C", "B", "K"):
            yield slug, cat, name


def build(xlsx: Path, edition: str):
    places = defaultdict(set)
    for slug, cat, name in read_codifier(xlsx):
        places[norm(name)].add((REGIONS.index(slug), cat))
    out = {"_comment": "Generated by src/build_gazetteer.py from the KATOTTG codifier. Do not edit; add to geo/gazetteer_extra.json.",
           "edition": edition, "regions": REGIONS,
           "places": {k: ",".join(f"{i}{c}" for i, c in sorted(v)) for k, v in sorted(places.items())}}
    GEO.mkdir(exist_ok=True)
    p = GEO / "gazetteer_ua.json"
    p.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    n_c = sum(1 for v in places.values() for _, c in v if c in "KM")
    print(f"{len(places)} names ({n_c} city entries) -> {p} ({p.stat().st_size // 1024} KB)")


def load():
    g = json.loads((GEO / "gazetteer_ua.json").read_text(encoding="utf-8"))
    extra = json.loads((GEO / "gazetteer_extra.json").read_text(encoding="utf-8"))
    places = {k: [(g["regions"][int(e[:-1])], e[-1]) for e in v.split(",")] for k, v in g["places"].items()}
    return places, extra


def resolve(name: str, places=None, extra=None):
    """Place name as written -> oblast slug, or None if unknown/ambiguous. Cities win over villages of the same name.
    >>> resolve("Харків"), resolve("Златопіль"), resolve("Кривий Ріг"), resolve("Миколаїв"), resolve("Харьков")
    ('kharkivska', 'kharkivska', 'dnipropetrovska', 'mykolaivska', None)
    """
    if places is None:
        places, extra = load()
    k = norm(name)
    if k in extra["aliases"]:
        return extra["aliases"][k]
    if k in extra["prefer"]:
        return extra["prefer"][k]
    hits = places.get(k, [])
    for level in ("KM", "XB", "C"):
        regs = {r for r, c in hits if c in level}
        if regs:
            return regs.pop() if len(regs) == 1 else None
    return None


def forms(name: str):
    """Approximate Ukrainian case forms of a city name (nominative + genitive/dative/locative/instrumental)."""
    n = name
    if " " in n:
        return {n}
    out = {n}
    if n.endswith("піль"):
        b = n[:-4] + "пол"
        out |= {b + "я", b + "і", b + "ем"}
    elif n.endswith("їв"):
        b = n[:-2]
        out |= {b + "єва", b + "єві", b + "євом"}
    elif n.endswith("ів"):
        b = n[:-2]
        out |= {b + "ова", b + "ові", b + "овом", b + "ову"}
    elif n.endswith("ь"):
        b = n[:-1]
        out |= {b + "я", b + "ю", b + "і", b + "ем"}
    elif n.endswith("ий"):
        b = n[:-2]
        out |= {b + "ого", b + "ому", b + "ім", b + "им"}
    elif n.endswith("е") and len(n) > 3 and n[-2] in "нвськ":
        b = n[:-1]
        out |= {b + "ого", b + "ому", b + "им"}
    elif n.endswith("ія"):  # Балаклія -> Балаклії, Балаклію, Балаклією
        b = n[:-1]
        out |= {b + "ї", b + "ю", b + "єю"}
    elif n.endswith("я"):
        b = n[:-1]
        out |= {b + "і", b + "ю", b + "ям", b + "ею"}
    elif n.endswith("а"):
        b = n[:-1]
        alt = {"к": "ц", "г": "з", "х": "с"}.get(b[-1:], b[-1:])
        out |= {b + "и", b + "і", b[:-1] + alt + "і", b + "у", b + "ою"}
    elif n.endswith("о"):
        b = n[:-1]
        out |= {b + "а", b + "і", b + "у", b + "ом"}
    elif n.endswith("и"):
        b = n[:-1]
        out |= {b, b + "ах", b + "ам", b + "ами"}
    elif n.endswith("і"):
        b = n[:-1]
        out |= {b + "ів", b + "ях", b + "ям", b + "ями"}
    elif re.search(r"[бвгґджзклмнпрстфхцчшщ]$", n):
        out |= {n + "а", n + "у", n + "і", n + "ом"}
    return {f for f in out if len(f) >= 4}


# Explicit letter class instead of \w / \m / \M: Postgres regex classes for Cyrillic depend on the database locale.
LETTER = "а-яіїєґёa-z'"
WORD_CH = f"[{LETTER}]"


def esc(s: str) -> str:
    """Escape regex metacharacters but keep '-', ' ' and the apostrophe literal (valid in Python re and Postgres ARE)."""
    return re.escape(s).replace("\\-", "-").replace("\\ ", " ").replace("\\'", "'")


def region_patterns():
    """slug -> list of regex alternatives (Postgres ARE and Python re; lowercase text, apostrophes normalised to ')."""
    places, extra = load()
    stop = set(extra["stoplist"])
    pats = defaultdict(set)
    for name, hits in places.items():
        cities = {r for r, c in hits if c in "KM"}
        if not cities or name in stop:
            continue
        if len(cities) > 1:
            if name not in extra["prefer"]:
                continue
            cities = {extra["prefer"][name]}
        r = cities.pop()
        if r not in OBLASTS:
            continue
        pats[r] |= {esc(f) for f in forms(name)}
    for alias, r in extra["aliases"].items():
        pats[r].add(esc(alias))
    for slug, o in OBLASTS.items():
        if o["shchyna"]:
            pats[slug].add(esc(o["shchyna"]) + WORD_CH + "{0,3}")
        if slug != "kyiv-city":
            pats[slug].add(esc(o["name"].lower()[:-1]) + WORD_CH + "{0,3} (обл|ова|ода)" + WORD_CH + "*")
    for stem, r in extra["ru_stems"].items():
        pats[r].add(esc(stem) + WORD_CH + "{0,4}")
    return {r: sorted(v) for r, v in sorted(pats.items())}


def sql_regex(alts):
    """One pattern per region, valid in both Postgres ARE (lookbehind since PG 9.6) and Python re."""
    return f"(?<!{WORD_CH})(" + "|".join(alts) + f")(?!{WORD_CH})"


def write_sql():
    pats = region_patterns()
    cases = ",\n    ".join(f"CASE WHEN x ~ '{sql_regex(v).replace(chr(39), chr(39) * 2)}' THEN '{r}' END" for r, v in pats.items())
    sql = f"""-- GENERATED by `python src/build_gazetteer.py --sql` from geo/gazetteer_ua.json (KATOTTG cities) + geo/gazetteer_extra.json.
-- Do not edit by hand: change the JSON and regenerate.
--
-- geo_regions(text) -> oblast slugs whose cities / oblast names the text mentions (case forms approximated, Russian
-- stems for the main cities). Used for region-specific rhetoric features (src/features.py, oblast panel).
-- rule_labels is NOT changed: its fixed six-city r_target feeds the frozen kh_missile_v1 / nat_massive_v1 specs, and a
-- frozen model's inputs must not move under it. The national regex lives next to it as rule_labels_geo.r_target_geo.
CREATE OR REPLACE FUNCTION geo_regions(t text) RETURNS text[] LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $f$
  SELECT array_remove(ARRAY[
    {cases}
  ], NULL)
  FROM (SELECT translate(lower(coalesce(t, '')), '’ʼ`‘', '''''''''') AS x) s
$f$;

CREATE OR REPLACE VIEW rule_labels_geo AS
SELECT r.*, g.regions AS target_regions, cardinality(g.regions) > 0 AS r_target_geo
FROM rule_labels r JOIN messages m ON m.id = r.message_id
CROSS JOIN LATERAL (SELECT geo_regions(m.text) AS regions) g;
"""
    p = ROOT / "db" / "migrations" / "016_rule_geo.sql"
    p.write_text(sql, encoding="utf-8")
    print(f"{sum(len(v) for v in pats.values())} alternatives in {len(pats)} regions -> {p} ({p.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--xlsx", help="local codifier file instead of downloading")
    ap.add_argument("--sql", action="store_true", help="regenerate db/migrations/016_rule_geo.sql")
    ap.add_argument("--skip-download", action="store_true", help="keep geo/gazetteer_ua.json as is")
    a = ap.parse_args()
    if not a.skip_download:
        if a.xlsx:
            src, edition = Path(a.xlsx), Path(a.xlsx).name
        else:
            edition = newest_url()
            src = ROOT / "data" / "kodyfikator.xlsx"
            src.parent.mkdir(exist_ok=True)
            print("downloading", edition)
            src.write_bytes(urllib.request.urlopen(urllib.request.Request(edition, headers=UA), timeout=180).read())
        build(src, edition)
    if a.sql:
        write_sql()
